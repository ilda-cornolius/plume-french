export function normalizeLemma(word: string): string {
  return word
    .normalize("NFC")
    .toLowerCase()
    .replace(/[’']/g, "'")
    .replace(/^l'|^d'|^j'|^s'|^n'|^c'|^m'|^t'/i, (m) => m.slice(0, -1));
}

/** Strip clitics like j'aime → try both full and after apostrophe */
export function glossCandidates(word: string): string[] {
  const n = word
    .normalize("NFC")
    .toLowerCase()
    .replace(/[’']/g, "'");
  const out = [n];
  const m = n.match(/^(l|d|j|s|n|c|m|t)'(.+)$/i);
  if (m) {
    out.push(m[1]);
    out.push(m[2]);
  }
  // aujourd'hui split often arrives as aujourd / hui
  if (n.startsWith("aujourd")) out.push("aujourd");
  return out;
}

