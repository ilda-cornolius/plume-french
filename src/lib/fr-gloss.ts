export function localGloss(word: string): string | null {
  for (const c of glossCandidates(word)) {
    if (LOCAL_GLOSS[c]) return LOCAL_GLOSS[c];
  }
  return null;
}

export function localIpa(word: string): string | null {
  for (const c of glossCandidates(word)) {
    if (LOCAL_IPA[c]) return LOCAL_IPA[c];
  }
  return null;
}

export function localWordInfo(word: string): Partial<WordInfo> {
  const en = localGloss(word);
  const ipa = localIpa(word);
  return {
    ...(en ? { en } : {}),
    ...(ipa ? { ipa } : {}),
  };
}

export function glossManyLocal(words: string[]): Record<string, string> {
  const out: Record<string, string> = {};
  for (const w of words) {
    const g = localGloss(w);
    if (g) out[w] = g;
  }
  return out;
}

export function infoManyLocal(words: string[]): Record<string, WordInfo> {
  const out: Record<string, WordInfo> = {};
  for (const w of words) {
    const en = localGloss(w);
    const ipa = localIpa(w);
    if (en || ipa) {
      out[w] = { en: en || "…", ipa: ipa || "" };
    }
  }
  return out;
}
